def transliterate_chinese_name(chinese_text: str) -> str:
    """Converts Chinese characters into standard Burmese phonetics using pypinyin."""
    try:
        syllables = pypinyin.lazy_pinyin(chinese_text)
        converted = "".join([PINYIN_TO_MY.get(s.lower(), s) for s in syllables])
        return converted
    except Exception:
        return chinese_text

